/**
 * 规划分析链路（planningAnalysis）的 AI 输出类型。
 *
 * 规划分析每回合在主剧情 + 状态 + 世界演变之后调用，统一审计章节状态与规划树，
 * 产出最小补丁：任务/事件/镜头/延续事项的 create/replace/delete 操作，以及可选的
 * 切章建议（必须通过代码门禁才应用）。
 */

import type {
  当前章节结构,
  下一章预告结构,
  历史章节结构,
  剧情换章规则结构,
  剧情任务结构,
  剧情待触发事件结构,
  剧情镜头结构,
  剧情延续事项结构,
} from "../../role_core/types/storyPlan";

/** 规划池条目类型。 */
export type 规划目标类型 = "task" | "event" | "camera" | "continuation";

/** 单条规划补丁操作。 */
export interface 规划更新操作 {
  目标: 规划目标类型;
  /** create=push 新条目；replace=按 id 覆盖（不存在则 push）；delete=按 id 删除。 */
  操作: "create" | "replace" | "delete";
  /** create 时来自条目.id；delete 时必填；replace 时优先取 id，其次条目.id。 */
  id?: string;
  条目?: 剧情任务结构 | 剧情待触发事件结构 | 剧情镜头结构 | 剧情延续事项结构;
}

/** 切章建议（代码门禁校验通过后才应用）。 */
export interface 切章建议 {
  新章节: 当前章节结构;
  新预告: 下一章预告结构;
  新换章规则: 剧情换章规则结构;
  /** 旧章归档条目（push 进历史卷宗）。 */
  归档: 历史章节结构;
  /** 是否清空当前章任务/事件/镜头池；跨章延续事项默认保留。 */
  清空规划池: boolean;
}

/** 规划分析一次调用的完整输出（解析后）。 */
export interface 规划分析输出 {
  thinking: string;
  /** 提供则整体替换当前章节（含推进状态 / 待解问题更新）。 */
  当前章节?: 当前章节结构 | null;
  /** 提供则整体替换下一章预告。 */
  下一章预告?: 下一章预告结构 | null;
  /** 提供则追加到历史卷宗（仅真正切章时提供）。 */
  历史卷宗追加?: 历史章节结构 | null;
  /** 切章建议（须通过切章门禁）。 */
  切章?: 切章建议 | null;
  /** 提供则整体替换当前章目标。 */
  当前章目标?: string[] | null;
  /** 规划池最小补丁操作。 */
  规划更新: 规划更新操作[];
}
